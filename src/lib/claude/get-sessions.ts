import { PROJECTS_PATH, getFolderDir } from '@lib/claude'
import { folderExists, join } from '@lib/utils'

const CHUNK_SIZE = 1024 * 1024
const SESSION_FILE = /^[0-9a-f-]{36}\.jsonl$/

export type Session = {
	id: string
	path: string
	folder: string
	dir: string | null
	title: string | null
	date: Date
}

/**
 * Return Claude Code sessions sorted from the most recent one. Only
 * project folders starting with the given prefix are read, if passed
 */

export async function getSessions(prefix = ''): Promise<Session[]> {
	if (!folderExists(PROJECTS_PATH)) {
		return []
	}

	const sessions: Session[] = []

	for await (const project of Deno.readDir(PROJECTS_PATH)) {
		if (!project.isDirectory || !project.name.startsWith(prefix)) {
			continue
		}

		const folder = join(PROJECTS_PATH, project.name)
		const dir = getFolderDir(project.name)

		for await (const entry of Deno.readDir(folder)) {
			if (!entry.isFile || !SESSION_FILE.test(entry.name)) {
				continue
			}

			const id = entry.name.replace(/\.jsonl$/, '')
			const path = join(folder, entry.name)

			const { mtime } = await Deno.stat(path)

			const tail = await readTail(path)

			sessions.push({
				id,
				path,
				folder,
				dir,
				title: await getTitle({ folder, id, tail }),
				date: mtime ?? new Date(0),
			})
		}
	}

	return sessions.sort((a, b) => b.date.getTime() - a.date.getTime())
}

/**
 * Get the custom title of the session or, if it has none, the last one
 * generated by Claude
 */

async function getTitle({
	folder,
	id,
	tail,
}: {
	folder: string
	id: string
	tail: string
}): Promise<string | null> {
	try {
		const { customTitle } = JSON.parse(
			await Deno.readTextFile(join(folder, id, 'custom-title.json'))
		)

		if (customTitle) {
			return customTitle
		}
	} catch {
		// No custom title
	}

	const lines = tail.split('\n')

	for (const line of lines.reverse()) {
		if (!line.includes('"ai-title"')) {
			continue
		}

		try {
			const { type, aiTitle } = JSON.parse(line)

			if (type === 'ai-title' && aiTitle) {
				return aiTitle
			}
		} catch {
			// Partial line at the start of the chunk
		}
	}

	return null
}

/**
 * Read the last chunk of a file
 */

async function readTail(path: string): Promise<string> {
	const file = await Deno.open(path)

	try {
		const { size } = await file.stat()

		await file.seek(Math.max(0, size - CHUNK_SIZE), Deno.SeekMode.Start)

		const buffer = new Uint8Array(Math.min(size, CHUNK_SIZE))

		let read = 0

		while (read < buffer.length) {
			const count = await file.read(buffer.subarray(read))

			if (count === null) {
				break
			}

			read += count
		}

		return new TextDecoder().decode(buffer.subarray(0, read))
	} finally {
		file.close()
	}
}
